/**
 * Modern Fisher-Yates shuffle algorithm
 */
function shuffleArray<T>(array: T[]): T[] {
  const result = [...array];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

/**
 * Randomly pick N distinct items from an array
 */
function pickRandomN<T>(array: T[], n: number): T[] {
  const shuffled = shuffleArray(array);
  return shuffled.slice(0, Math.min(n, shuffled.length));
}

/**
 * Transforms a raw question into a full TaskDefinition:
 * 1. Shuffles its 4 options so they appear in randomized order.
 * 2. Assigns hotspots to the 4 shuffled options.
 * 3. Assigns questionNumber (1..25) and topicQuestionIndex (1..5).
 */
export function buildTaskFromRaw(
  raw: RawQuestionDefinition,
  globalQuestionIndex: number,
  topicQuestionIndex: number
): TaskDefinition {
  const topic = ENGINEERING_TOPICS.find((t) => t.id === raw.topicId) || ENGINEERING_TOPICS[0];

  // 1. Shuffled 4 options
  const shuffledOptions = shuffleArray(raw.options);

  // 2. Build ToolDefinitions
  const availableTools: ToolDefinition[] = shuffledOptions.map((opt) => ({
    ...opt,
    isCorrect: opt.id === raw.correctToolId,
  }));

  // 3. Build Hotspots corresponding to the 4 shuffled options
  const workspaceHotspots: WorkspaceHotspot[] = DEFAULT_4_HOTSPOTS.map((h, i) => {
    const tool = availableTools[i] || availableTools[0];
    return {
      ...h,
      toolId: tool.id,
      label: tool.name,
      ariaLabel: `${tool.name} on workbench`,
    };
  });

  return {
    id: `${raw.id}-s${Date.now().toString(36)}-${Math.random().toString(36).substring(2, 6)}`,
    topicId: raw.topicId,
    topicName: topic.name,
    questionNumber: globalQuestionIndex,
    topicQuestionIndex,
    title: raw.title,
    environmentName: `${topic.name} Bench`,
    environmentImage: topic.environmentImage,
    mission: raw.mission,
    description: raw.description,
    difficulty: raw.difficulty,
    phase: `${topic.name} • Q${topicQuestionIndex}/5`,
    availableTools,
    workspaceHotspots,
    correctToolId: raw.correctToolId,
    instructionalFeedbackOnSuccess: raw.successFeedback,
  };
}

/**
 * Generates the full 25-question assessment by:
 * 1. Selecting 5 random questions out of 15 for each of the 5 trades (5 x 5 = 25 questions).
 * 2. Randomizing the 4 options sequence for each question.
 */
export function generateRandomizedEngineeringAssessment(): TaskDefinition[] {
  const tradesOrder: EngineeringTradeId[] = ['electrical', 'mechanical', 'civil', 'software', 'metallurgy'];
  const assessmentQuestions: TaskDefinition[] = [];

  let globalIndex = 1;

  for (const tradeId of tradesOrder) {
    const tradeBank = QUESTION_BANK_BY_TRADE[tradeId] || [];
    // Select 5 random questions from the 15 available in the bank
    const selected5Questions = pickRandomN(tradeBank, 5);

    selected5Questions.forEach((rawQ, idx) => {
      const task = buildTaskFromRaw(rawQ, globalIndex, idx + 1);
      assessmentQuestions.push(task);
      globalIndex++;
    });
  }

  return assessmentQuestions;
}

// Baseline static fallback export for tests or initial hydration
export const ALL_ENGINEERING_QUESTIONS: TaskDefinition[] = generateRandomizedEngineeringAssessment();
